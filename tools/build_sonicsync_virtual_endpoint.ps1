param(
    [Parameter(Mandatory = $true)]
    [string] $OutputDirectory
)

$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$source = Join-Path $repo 'drivers\sonicsync-virtual-endpoint\sysvad'
$output = [IO.Path]::GetFullPath($OutputDirectory)
$work = Join-Path $output 'source'
$marker = Join-Path $output '.sonicsync-driver-build-marker'
New-Item -ItemType Directory -Force -Path $output | Out-Null

$vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
if (-not (Test-Path $vswhere)) { throw "vswhere.exe missing: $vswhere" }
$vs = & $vswhere -latest -products '*' -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 Component.Microsoft.Windows.DriverKit.BuildTools -property installationPath
if (-not $vs) { throw 'Visual Studio with MSVC x64/x86 and WDK BuildTools components was not found.' }
$msbuild = Join-Path $vs 'MSBuild\Current\Bin\amd64\MSBuild.exe'
if (-not (Test-Path $msbuild)) { throw "64-bit MSBuild missing: $msbuild" }

$wdk = Join-Path $env:USERPROFILE '.nuget\packages\microsoft.windows.wdk.x64\10.0.26100.6584\c'
$sdk = Join-Path ${env:ProgramFiles(x86)} 'Windows Kits\10'
$sdkVersion = '10.0.26100.0'
$sdkBin = Join-Path $sdk "bin\$sdkVersion"
$required = @(
    (Join-Path $wdk 'build\WindowsDriver.Common.targets'),
    (Join-Path $wdk 'Include\10.0.26100.0\km\portcls.h'),
    (Join-Path $wdk 'tools\10.0.26100.0\x64\infverif.exe'),
    (Join-Path $wdk 'bin\10.0.26100.0\x86\Inf2Cat.exe'),
    (Join-Path $sdk "Include\$sdkVersion\um\Windows.h"),
    (Join-Path $sdkBin 'x86\rc.exe')
)
foreach ($path in $required) {
    if (-not (Test-Path $path)) { throw "Required SDK/WDK component not found: $path" }
}

if (Test-Path $work) {
    if (-not (Test-Path $marker)) { throw "Refusing to replace unmarked staging directory: $work" }
    if ([IO.Path]::GetFullPath($work) -ne [IO.Path]::GetFullPath((Join-Path $output 'source'))) {
        throw "Staging directory is outside the expected build output: $work"
    }
    Remove-Item -LiteralPath $work -Recurse -Force
}
New-Item -ItemType Directory -Force -Path $work | Out-Null
Set-Content -LiteralPath $marker -Value 'Generated by tools/build_sonicsync_virtual_endpoint.ps1' -Encoding Ascii
& robocopy.exe $source $work /E /XD x64 ARM64 Debug Release .git /NFL /NDL /NJH /NJS /NP | Out-Null
if ($LASTEXITCODE -ge 8) { throw "Could not stage driver sources for build (robocopy exit $LASTEXITCODE)." }

$log = Join-Path $output 'build.log'
Remove-Item -LiteralPath $log -Force -ErrorAction SilentlyContinue
$common = @(
    '/m', '/verbosity:minimal', '/p:Configuration=Debug', '/p:Platform=x64',
    '/p:VCToolsVersion=14.29.30133', '/p:WindowsTargetPlatformVersion=10.0.26100.0',
    "/p:WindowsSdkDir=$sdk/", "/p:WindowsSdkDir_10=$sdk/",
    "/p:WDKContentRoot=$wdk/", '/p:WDKBuildFolder=10.0.26100.0',
    "/p:WDKBinRoot=$wdk/bin/10.0.26100.0/", '/p:KMDF_VERSION_MINOR=33',
    "/p:RCToolPath=$sdkBin/x86/", '/p:RCToolExe=rc.exe', '/p:RCToolArchitecture=Native32Bit',
    "/p:InfToolPath=$wdk/bin/10.0.26100.0/x64/", '/p:InfToolArchitecture=Native64Bit',
    "/p:Inf2CatToolPath=$wdk/bin/10.0.26100.0/x86/", '/p:Inf2CatToolArchitecture=Native32Bit',
    '/p:SkipPackageVerification=false', '/p:SignMode=Off', '/p:EnableTestSign=false'
)

$projects = @(
    (Join-Path $work 'EndpointsCommon\EndpointsCommon.vcxproj'),
    (Join-Path $work 'Package\package.VcxProj')
)
foreach ($project in $projects) {
    if (-not (Test-Path $project)) { throw "Driver project missing: $project" }
    Write-Host "Building $([IO.Path]::GetFileName($project)) with package verification enabled..."
    & $msbuild $project @common 2>&1 | Tee-Object -FilePath $log -Append
    if ($LASTEXITCODE -ne 0) { throw "MSBuild failed ($LASTEXITCODE); see $log" }
}

$packageInf = Join-Path $work 'Package\x64\Debug\package\SonicSyncVirtualAudio.inf'
$infVerifier = Join-Path $wdk 'tools\10.0.26100.0\x64\infverif.exe'
if (-not (Test-Path $packageInf)) { throw "Packaged INF missing: $packageInf" }
Write-Host 'Running strict InfVerif /h on the packaged INF...'
& $infVerifier /h $packageInf 2>&1 | Tee-Object -FilePath $log -Append
if ($LASTEXITCODE -ne 0) { throw "InfVerif /h failed ($LASTEXITCODE); see $log" }

$artifacts = Get-ChildItem -Path $work -Recurse -File | Where-Object Extension -in '.sys', '.cat', '.inf'
if (-not ($artifacts | Where-Object Extension -eq '.sys')) { throw 'Build completed without a driver SYS artifact.' }
Write-Host "Build and enabled WDK package verification completed. Log: $log"
Write-Host 'Generated driver/catalog files are unsigned; this target does not install or sign them.'
$artifacts | ForEach-Object {
    $sha = [Security.Cryptography.SHA256]::Create()
    $stream = [IO.File]::OpenRead($_.FullName)
    try { $hash = ([BitConverter]::ToString($sha.ComputeHash($stream))).Replace('-', '') }
    finally { $stream.Dispose(); $sha.Dispose() }
    '{0} | {1} bytes | unsigned by build configuration | SHA256 {2}' -f $_.FullName, $_.Length, $hash
}
